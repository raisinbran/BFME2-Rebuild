// FUNCTION: BFME2 0x000DD71C size=60 name=?loadRoads@W3DRoadBuffer@@QAEXXZ evidence=N:ledger tier=B hypothesis:K
void W3DRoadBuffer::loadRoads()
{
	if (!m_initialized) {
		return;
	}
	// Free any existing road segments.
	clearAllRoads();
	addMapObjects();
	updateCountsAndFlags();
	insertTeeIntersections();
	insertCurveSegments();
	insertCrossTypeJoins();
	preloadRoadsInVertexAndIndexBuffers();
	m_updateBuffers = true;
}

